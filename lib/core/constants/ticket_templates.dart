class TicketLanguage {
  const TicketLanguage(this.code, this.nativeName, {this.rtl = false});

  final String code;
  final String nativeName;
  final bool rtl;
}

/// All wording for one language. "{x}" is replaced by the allergen list.
class TicketCopy {
  const TicketCopy({
    required this.title,
    required this.intro,
    required this.anaphylacticHeading,
    required this.severeHeading,
    required this.preferenceHeading,
    required this.anaphylacticLines,
    required this.severeLines,
    required this.preferenceLines,
    required this.closing,
    required this.footer,
    required this.listSeparator,
    required this.allergens,
  });

  final String title;
  final String intro;
  final String anaphylacticHeading;
  final String severeHeading;
  final String preferenceHeading;
  final List<String> anaphylacticLines;
  final List<String> severeLines;
  final List<String> preferenceLines;
  final String closing;
  final String footer;
  final String listSeparator;

  /// Keyed by the allergen name stored in the database.
  final Map<String, String> allergens;
}

